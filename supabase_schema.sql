CREATE POLICY "Acesso Total Raffles" ON public.raffles FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Acesso Total Raffle Numbers" ON public.raffle_numbers FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Acesso Total Raffle Prizes" ON public.raffle_prizes FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Acesso Total Vales" ON public.vales_prizes FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Acesso Total Transactions" ON public.vale_transactions FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Acesso Total Fishing" ON public.fishing_bookings FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Acesso Total Rancho" ON public.rancho_bookings FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Acesso Total Eduardo" ON public.eduardo_work_days FOR ALL USING (true) WITH CHECK (true);
